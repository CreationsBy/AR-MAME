"""An original Z80 graphics/input diagnostic. Contains no commercial ROM bytes.

The program copies our board into video RAM and moves one yellow sprite in response
to the actual machine input ports. It is a diagnostic, not Pac-Man gameplay.
"""
from pathlib import Path
import zipfile

def program():
    code = bytearray()
    labels, branches = {}, []
    def emit(*values): code.extend(values)
    def label(name): labels[name] = len(code)
    def jr(opcode, target):
        emit(opcode, 0); branches.append((len(code)-1, target))
    emit(0xf3, 0x31, 0xf0, 0x4f)          # DI; LD SP,4ff0
    emit(0xaf, 0x32, 0x00, 0x50, 0x32, 0x03, 0x50)  # IRQ/flip off
    emit(0x21, 0x00, 0x10, 0x11, 0x00, 0x40, 0x01, 0x00, 0x04, 0xed, 0xb0)  # board -> VRAM
    emit(0x21, 0x00, 0x44, 0x11, 0x01, 0x44, 0x01, 0xff, 0x03, 0x36, 0x01, 0xed, 0xb0)  # colors
    emit(0x3e, 0x02, 0x32, 0xf1, 0x4f)   # sprite color 2
    emit(0x16, 0x8f, 0x1e, 0x80)          # D/E sprite coordinates
    label("loop")
    emit(0x3a, 0xc0, 0x50)                # reset watchdog
    emit(0x3a, 0x00, 0x50, 0x2f, 0xe6, 0x0f, 0x47)  # read active-low input bits -> B
    for bit, instruction in [(0,0x1d), (3,0x1c), (1,0x15), (2,0x14)]:
        emit(0xcb, 0x40 + bit * 8)        # BIT bit,B
        jr(0x28, f"skip{bit}")
        emit(instruction)                # DEC E, INC E, DEC D, INC D
        label(f"skip{bit}")
    emit(0x7a, 0x32, 0x60, 0x50, 0x7b, 0x32, 0x61, 0x50)
    emit(0x01, 0x00, 0x08)                # LD BC,2048; bounded CPU delay
    label("delay")
    emit(0x0b, 0x78, 0xb1)                # DEC BC; LD A,B; OR C
    jr(0x20, "delay")
    emit(0xc3, labels["loop"] & 255, labels["loop"] >> 8)
    for offset, target in branches:
        delta = labels[target] - offset - 1
        if not -128 <= delta <= 127: raise ValueError("Z80 branch out of range")
        code[offset] = delta & 255
    return bytes(code)

def board():
    data = bytearray(1024)
    for row in range(28):
        for col in range(36):
            r, c = row + 2, col - 2
            offset = r + ((c & 31) << 5) if c & 32 else c + (r << 5)
            wall = row in (2,25) or col in (2,33) or (row % 6 == 0 and 4 < col < 31 and col % 7 > 1)
            if wall: data[offset] = 1
    return bytes(data)

def driver_source():
    lines = ["\n/* AR-MAME original diagnostic: generated from scripts/make_diagnostic.py. */", "ROM_START( armtest )",
             "ROM_REGION(0x10000, REGION_CPU1, 0)", "ROM_FILL(0, 0x10000, 0)"]
    for base, data in [(0, program()), (0x1000, board())]:
        for offset, value in enumerate(data):
            if value: lines.append(f"ROM_FILL(0x{base+offset:04x}, 1, 0x{value:02x})")
    lines.extend([
        "ROM_REGION(0x2000, REGION_GFX1, 0)", "ROM_FILL(0, 0x2000, 0)",
        "ROM_FILL(16, 16, 0xff)", "ROM_FILL(0x1000, 64, 0xff)",
        "ROM_REGION(0x120, REGION_PROMS, 0)", "ROM_FILL(0, 0x120, 0)",
        "ROM_FILL(1, 1, 0x3f)", "ROM_FILL(2, 1, 0xc0)",  # yellow and blue palettes
        "ROM_FILL(0x27, 1, 2)", "ROM_FILL(0x2b, 1, 1)", # tile/sprite lookup pen 3
        "ROM_REGION(0x200, REGION_SOUND1, 0)", "ROM_FILL(0, 0x200, 0)",
        "ROM_END", 'GAME(2026, armtest, 0, pacman, pacman, 0, ROT90, "AR-MAME", "AR-MAME Original Z80 Diagnostic")',
    ])
    return "\n".join(lines) + "\n"

def write_container(path):
    path = Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("README.txt", "Original AR-MAME diagnostic. Program/graphics generated by our core build; no commercial ROMs.\n")

if __name__ == "__main__":
    root = Path(__file__).resolve().parents[1]
    write_container(root / "ios/Resources/armtest.zip")
